const patternOf = (path: string) =>
  new RegExp(
    `^${path.replace(/:\w+(\{[^}]+\})?/g, (_, inner?: string) => (inner ? `(${inner.slice(1, -1)})` : "[^/]+"))}$`,
  );

const STEP_UP_ROUTES = Object.entries(ROUTE_ACCESS)
  .filter(([, access]) => access === "stepUp")
  .map(([route]) => {
    const [method, path] = route.split(" ") as [string, string];
    return { method, pattern: patternOf(path) };
  });

function needsStepUp(method: string, path: string): boolean {
  return STEP_UP_ROUTES.some((route) => route.method === method && route.pattern.test(path));
}

export function stepUpGuard(prefix = "/api/v1"): MiddlewareHandler<AppEnv> {
  return async (c, next) => {
    const path = c.req.path.startsWith(prefix) ? c.req.path.slice(prefix.length) : c.req.path;
    if (needsStepUp(c.req.method, path)) assertStepUp(c);
    await next();
  };
}
