const ROOT = path.resolve(import.meta.dirname, "..");
const cutDir = (name) =>
  process.env.SCENE
    ? path.resolve(ROOT, process.env.FILM_OUT ?? ".film/index")
    : path.resolve(ROOT, process.env.FILM_OUT ?? ".film", name);
const built = {};
const read = (p) => readFileSync(path.join(ROOT, p), "utf8");
const FILM_SIZE = { h: { w: 1920, h: 1080 }, v: { w: 1080, h: 1920 } };

const dom = new JSDOM("<!doctype html><body></body>");
const doc = dom.window.document;

export function loadSnap(name) {
  const file = `snap/${name}.html`;
  const box = doc.createElement("div");
  if (!existsSync(path.join(ROOT, file))) {
    console.warn(`  missing snapshot ${file}: placeholder used`);
    box.innerHTML = `<div class="appbody" style="background:#eee;font:20px sans-serif;padding:40px">${file}</div>`;
    return box.firstElementChild;
  }
  box.innerHTML = read(file);
  return box.firstElementChild;
}

function buildAppCss(mode) {
  const dir = path.join(ROOT, "assets/.css", mode);
  if (!existsSync(dir)) return;
  const root = postcss.root();
  const seen = new Set();
  const layers = new Map();
  for (const f of readdirSync(dir).sort()) {
    for (const node of postcss.parse(repairSelectors(readFileSync(path.join(dir, f), "utf8")))
      .nodes) {
      if (node.type === "atrule" && node.name === "layer" && node.nodes) {
        if (!layers.has(node.params)) {
          layers.set(node.params, postcss.atRule({ name: "layer", params: node.params }));
          root.append(layers.get(node.params));
        }
        for (const child of node.nodes) {
          const key = `${node.params}|${child.toString()}`;
          if (seen.has(key)) continue;
          seen.add(key);
          layers.get(node.params).append(child.clone());
        }
      } else {
        const key = node.toString();
        if (seen.has(key)) continue;
        seen.add(key);
        root.append(node.clone());
      }
    }
  }
  root.walkDecls((d) => {
    if (/^(transition|animation)(-|$)/.test(d.prop)) {
      d.remove();
      return;
    }
    if (d.prop.includes("font"))
      d.value = d.value
        .replace(
          /,\s*"?(Apple Color Emoji|Segoe UI Emoji|Segoe UI Symbol|Noto Color Emoji)"?/gi,
          "",
        )
        .replace(/ui-monospace,\s*SFMono-Regular.*monospace/is, '"JetBrains Mono", monospace')
        .replace(/"?Cascadia Mono"?.*monospace/is, '"JetBrains Mono", monospace');
  });
  root.walkRules((r) => {
    if (r.selector.includes("[style]")) r.remove();
  });
  writeFileSync(
    path.join(ROOT, `assets/app.${mode}.film.css`),
    `/* Generated by tools/build.mjs from assets/.css/${mode}. Do not edit. */\n${root.toString()}\n`,
  );
}

let uid = 0;
function scopeIds(el, scope) {
  const html = el.innerHTML;
  const used = new Set(
    [...html.matchAll(/url\(["']?#([^"')]+)["']?\)/g), ...html.matchAll(/href="#([^"]+)"/g)].map(
      (m) => m[1],
    ),
  );
  const n = uid++;
  for (const node of el.querySelectorAll("[id]")) {
    if (used.has(node.id)) node.id = `${scope}-${n}-${node.id}`;
    else node.removeAttribute("id");
  }
  for (const node of el.querySelectorAll("*")) {
    for (const a of [
      "for",
      "aria-labelledby",
      "aria-describedby",
      "aria-controls",
      "aria-owns",
      "aria-activedescendant",
    ])
      node.removeAttribute(a);
    for (const a of [
      "href",
      "xlink:href",
      "style",
      "fill",
      "stroke",
      "clip-path",
      "mask",
      "filter",
    ]) {
      const v = node.getAttribute(a);
      if (!v || !v.includes("#")) continue;
      node.setAttribute(
        a,
        v
          .replace(/url\((["']?)#([^"')]+)\1\)/g, (m, q, id) =>
            used.has(id) ? `url(#${scope}-${n}-${id})` : m,
          )
          .replace(/^#(.+)$/, (m, id) => (used.has(id) ? `#${scope}-${n}-${id}` : m)),
      );
    }
    if (node.tagName === "A") node.removeAttribute("href");
  }
}

function buildScene(file, id, fmt) {
  const src = read(file);
  const dur = Number(/<!--\s*scene:\s*dur=([\d.]+)\s*-->/.exec(src)?.[1]);
  if (!dur) throw new Error(`${file}: missing <!-- scene: dur=N -->`);
  const style = /<style>([\s\S]*?)<\/style>/.exec(src)?.[1] ?? "";
  const script = /<script>([\s\S]*)<\/script>/.exec(src)?.[1] ?? "";
  const body = src
    .replace(/<!--\s*scene:[^>]*-->/, "")
    .replace(/<style>[\s\S]*?<\/style>/, "")
    .replace(/<script>[\s\S]*<\/script>/, "");

  const box = doc.createElement("div");
  box.innerHTML = body;
  for (const el of box.querySelectorAll(".vp, .appwin, .phone")) {
    el.setAttribute("data-layout-ignore", "");
    el.setAttribute("data-layout-allow-overflow", "");
    el.setAttribute("data-layout-allow-occlusion", "");
    el.setAttribute("data-layout-allow-overlap", "");
  }
  for (const win of box.querySelectorAll("[data-snap]")) {
    const snap = loadSnap(win.getAttribute("data-snap"));
    win.removeAttribute("data-snap");
    win.appendChild(snap);
    fixes.always(win, { loadSnap, doc, args: [] });
    for (const el of win.querySelectorAll('[style*="font-family"]'))
      el.style.fontFamily = /mono|cascadia|courier/i.test(el.style.fontFamily)
        ? '"JetBrains Mono", monospace'
        : el.style.fontFamily;
    for (const call of (win.getAttribute("data-fix") ?? "")
      .split(";")
      .map((s) => s.trim())
      .filter(Boolean)) {
      const [name, ...args] = call.split(":").map((s) => s.trim());
      if (!fixes[name]) throw new Error(`${file}: unknown fix "${name}"`);
      fixes[name](win, { loadSnap, doc, args });
    }
    win.removeAttribute("data-fix");
    scopeIds(win, id);
  }

  const { w, h } = FILM_SIZE[fmt];
  const out = `<template>
  <style>
    #root {
      position: absolute;
      inset: 0;
    }
${style}
  </style>
  <div id="root" data-composition-id="${id}" data-width="${w}" data-height="${h}">
${box.innerHTML}
  </div>
  <script>
${script.replaceAll("{{id}}", id).replaceAll("{{dur}}", String(dur))}
  </script>
</template>
`;
  built[id] = out;
  return dur;
}

function buildCut(name, cut, durs) {
  const { w, h } = FILM_SIZE[cut.fmt];
  const dir = cutDir(name);
  rmSync(path.join(dir, "compositions"), { recursive: true, force: true });
  mkdirSync(path.join(dir, "compositions"), { recursive: true });
  for (const link of ["assets", "lib", "android"])
    if (!existsSync(path.join(dir, link))) symlinkSync(path.join(ROOT, link), path.join(dir, link));
  for (const f of ["hyperframes.json", "meta.json"]) writeFileSync(path.join(dir, f), read(f));
  for (const [id] of cut.scenes)
    writeFileSync(path.join(dir, "compositions", `${id}.html`), built[id]);
  let t = 0;
  const hosts = cut.scenes.map(([id, slot, a, b], i) => {
    const d = slot ?? durs[id];
    const trim = ` data-film-start="${+t.toFixed(3)}" data-film-slot="${d}" data-film-in="${a ?? 0}" data-film-out="${b ?? durs[id]}"`;
    const host = `      <div
        id="${id}"
        data-composition-id="${id}"
        data-composition-src="compositions/${id}.html"
        data-start="${+t.toFixed(3)}"
        data-duration="${d}"
        data-track-index="1"
        data-track-kind="graphics"
        data-width="${w}"
        data-height="${h}"${trim}
        style="z-index: ${i + 1}"
      ></div>`;
    t += d;
    return host;
  });
  const total = +t.toFixed(3);
  const audio = ["music", "sfx"]
    .filter((kind) => existsSync(path.join(ROOT, `assets/audio/${kind}.${name}.wav`)))
    .map(
      (kind, i) => `      <audio
        id="${kind}"
        class="clip"
        src="assets/audio/${kind}.${name}.wav"
        data-start="0"
        data-duration="${total}"
        data-track-index="${i + 2}"
        data-volume="1"
      ></audio>`,
    );
  const html = `<!doctype html>
<!-- Generated by tools/build.mjs from src/cuts.mjs. Edit those, not this file. -->
<html lang="en" data-fmt="${cut.fmt}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${w}, height=${h}" />
    <title>tiny-agents: ${cut.title}</title>
    <script src="assets/vendor/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/app.${cut.fmt === "h" ? "desktop" : "mobile"}.film.css" />
    <link rel="stylesheet" href="lib/film.css" />
    <script src="lib/film.js"></script>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="${w}" data-height="${h}">
${hosts.join("\n")}
${audio.join("\n")}
    </div>
    <script>
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
  writeFileSync(path.join(dir, "index.html"), html);
  return total;
}

const GSAP = "https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js";
const gsapFile = path.join(ROOT, "assets/vendor/gsap.min.js");
if (!existsSync(gsapFile)) {
  mkdirSync(path.dirname(gsapFile), { recursive: true });
  execFileSync("curl", ["-fsSL", "--retry", "3", "-m", "60", "-o", gsapFile, GSAP]);
}

buildAppCss("desktop");
buildAppCss("mobile");
const durs = {};
const want = new Set(Object.values(CUTS).flatMap((c) => c.scenes.map((s) => s[0])));
for (const [dir, fmt] of [
  ["src/scenes", "h"],
  ["src/scenes/v", "v"],
]) {
  if (!existsSync(path.join(ROOT, dir))) continue;
  for (const f of readdirSync(path.join(ROOT, dir))
    .filter((f) => f.endsWith(".html"))
    .sort()) {
    const id = path.basename(f, ".html");
    if (!want.has(id)) continue;
    durs[id] = buildScene(`${dir}/${f}`, id, fmt);
  }
}
for (const [name, cut] of Object.entries(CUTS)) {
  const missing = cut.scenes.filter(([id]) => !(id in durs)).map(([id]) => id);
  if (missing.length) {
    console.log(`${name}: skipped, no source yet for ${missing.join(", ")}`);
    continue;
  }
  console.log(
    `${name}: ${buildCut(name, cut, durs)} s, ${cut.scenes.length} scenes -> ${path.relative(ROOT, cutDir(name))}/`,
  );
}
